"""Replay stock R002 configuration offline and emit the ordered MMIO writes."""

import argparse
from pathlib import Path
import struct

from unicorn import Uc, UC_ARCH_ARM, UC_MODE_ARM, UC_HOOK_CODE, UC_HOOK_MEM_WRITE
from unicorn.arm_const import (UC_ARM_REG_LR, UC_ARM_REG_PC, UC_ARM_REG_R0,
                               UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3,
                               UC_ARM_REG_SP)


IMAGE = 0xC0008000
MMIO = 0xF8C80000
HAL = 0x10000000
JOB = HAL + 0x1000
OSAL = HAL + 0x2000
ALLOC = HAL + 0x3000
STOP = HAL + 0x4000
ARGS = (UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3)


def extract(image, symbols):
    sym = {fields[2]: int(fields[0], 16) for line in symbols.splitlines()
           if len(fields := line.split()) >= 3}
    cpu = Uc(UC_ARCH_ARM, UC_MODE_ARM)
    cpu.mem_map(IMAGE, 0x02000000)
    cpu.mem_map(HAL, 0x10000)
    cpu.mem_map(MMIO, 0x10000)
    cpu.mem_write(IMAGE, image)
    writes = []

    def write_words(addr, *values):
        cpu.mem_write(addr, struct.pack(f"<{len(values)}I", *values))

    def stub(_cpu, pc, _size, _data):
        a, b, c, d = (cpu.reg_read(reg) for reg in ARGS)
        if pc == sym["venc_drv_osal_get_g_venc_osal_func_ptr"]:
            result = OSAL
        elif pc == ALLOC:
            assert a == 0xc50
            result = HAL
        elif pc == sym["memset_s"]:
            assert d <= b
            cpu.mem_write(a, bytes([c]) * d)
            result = 0
        elif pc == sym["memcpy_s"]:
            assert d <= b
            cpu.mem_write(a, bytes(cpu.mem_read(c, d)))
            result = 0
        elif pc == sym["__aeabi_uidiv"]:
            result = a // b
        else:
            return
        cpu.reg_write(UC_ARM_REG_R0, result)
        cpu.reg_write(UC_ARM_REG_PC, cpu.reg_read(UC_ARM_REG_LR))

    for address in [ALLOC, *(sym[name] for name in ("venc_drv_osal_get_g_venc_osal_func_ptr",
                                                    "memset_s", "memcpy_s", "__aeabi_uidiv"))]:
        cpu.hook_add(UC_HOOK_CODE, stub, begin=address, end=address)

    def capture(_cpu, _access, address, size, value, _data):
        assert size == 4 and address % 4 == 0
        writes.append((address - MMIO, value & 0xffffffff))

    cpu.hook_add(UC_HOOK_MEM_WRITE, capture, begin=MMIO, end=MMIO + 0xffff)

    def call(name, arg=0):
        cpu.reg_write(UC_ARM_REG_SP, HAL + 0xff00)
        cpu.reg_write(UC_ARM_REG_LR, STOP)
        cpu.reg_write(UC_ARM_REG_R0, arg)
        cpu.emu_start(sym[name], STOP, count=100000)
        assert cpu.reg_read(UC_ARM_REG_PC) == STOP, name
        return cpu.reg_read(UC_ARM_REG_R0)

    write_words(0xc1ae1d60, MMIO)
    write_words(OSAL + 0x0c, ALLOC)
    result = call("drv_venc_hal_v500_r002_init")
    assert result == 0
    assert not writes

    # Direct-mode job fields from venc_drv_efl_cfg_reg_venc and the HAL reads.
    for offset, value in {
        0x0c: 320, 0x10: 192, 0x3c: 1, 0x4c: 320, 0x50: 320,
        0x54: 61440, 0x58: 30720, 0x74: 320, 0x78: 320,
        0x8c: 128, 0x90: 12, 0x170: 64,
        0x244: 1, 0x24c: 28, 0x250: 28, 0x254: 28, 0x26c: 51,
    }.items():
        write_words(JOB + offset, value)
    call("drv_venc_hal_direct_cfg_reg", JOB)
    assert writes[0] == (0, 0x41) and writes[-1] == (8, 1)
    assert dict(writes)[0x018] == 0x100510c6
    assert dict(writes)[0x044] == 0x00bf013f
    assert dict(writes)[0x300] == 0x11140
    assert dict(writes)[0x23c] == 0

    # The probe owns IRQ, START and the complete SMMU window itself.
    return [(offset, value) for offset, value in writes if 0x00c <= offset < 0xf000]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path)
    parser.add_argument("symbols", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    writes = extract(args.image.read_bytes(), args.symbols.read_text())
    header = [
        "/* SPDX-License-Identifier: GPL-2.0-only */",
        "/* Generated by extract-registers.py. DMA addresses and headers are filled at runtime. */",
        "static const struct venc_reg r002_idr[] = {",
        *(f"\t{{ 0x{offset:03x}, 0x{value:08x} }}," for offset, value in writes),
        "};",
    ]
    args.output.write_text("\n".join(header) + "\n", encoding="ascii", newline="\n")
    print(f"{len(writes)} ordered encoder register writes")


if __name__ == "__main__":
    main()
